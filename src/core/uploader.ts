import Uppy, { type Meta, type UppyFile, type UppyOptions } from "@uppy/core";
import AwsS3, { type AwsBody, type AwsS3Options } from "@uppy/aws-s3";
import { Store } from "./store.js";
import { MAX_FILE_SIZE, MULTIPART_THRESHOLD, PART_SIZE, IMAGE_THUMBNAIL_THRESHOLD, DEFAULT_THUMBNAIL_DIMENSION, currentMonth, mediaType, thumbnailKey, uploadFilename, validateFile, validateMonth } from "../shared/media-types.js";
import type { MediaItem } from "../shared/media-types.js";
import type { MediaApi, SignRequest, UploadGrant } from "./api.js";
import { asError } from "../shared/errors.js";
import { openVideo, type VideoSource } from "./video.js";
import { openImage, type ImageSource, type CapturedThumbnail } from "./thumbnail.js";

interface ThumbnailSelection {
  kind: "image" | "video";
  enabled: boolean;
  maxDimension: number;
  dimensions?: string;
  abort: AbortController;
  source?: VideoSource;
  imageSource?: ImageSource;
  pending: Promise<void>;
  checking: boolean;
  time: number;
  posterId?: string;
  posterUrl?: string;
  error: string | null;
}

export interface QueuedFile {
  id: string;
  name: string;
  size: number;
  progress: number;
  complete: boolean;
  error: string | null;
  video?: { duration: number; time: number; posterUrl?: string; checking: boolean; editable: boolean };
  image?: { enabled: boolean; maxDimension: number; dimensions?: string; thumbnailUrl?: string; checking: boolean; editable: boolean };
}
export interface UploaderState {
  month: string;
  files: QueuedFile[];
  uploaded: MediaItem[];
  uploading: boolean;
  error: Error | null;
  summary: string;
}
export interface MediaUploaderOptions {
  month?: string;
  videoFactory?: (file: Blob, signal: AbortSignal) => Promise<VideoSource>;
  imageFactory?: (file: Blob, signal: AbortSignal) => Promise<ImageSource>;
  uppyFactory?: (options: Omit<UppyOptions<Meta, AwsBody>, "restrictions"> & {
    restrictions: Partial<NonNullable<UppyOptions<Meta, AwsBody>["restrictions"]>>;
  }) => Uppy<Meta, AwsBody>;
}

export class MediaUploader extends Store<UploaderState> {
  #grants = new Map<string, UploadGrant>();
  #proposals = new Map<string, UppyFile<Meta, AwsBody>>();
  #items = new Map<string, MediaItem>();
  #selections = new Map<string, ThumbnailSelection>();
  #finalized = new Set<string>();
  #metadataErrors = new Map<string, string>();
  #finishing: Promise<void> = Promise.resolve();
  #metadataAbort?: AbortController;
  #reported = new Set<string>();
  #addingPoster = false;
  #videoFactory: (file: Blob, signal: AbortSignal) => Promise<VideoSource>;
  #imageFactory: (file: Blob, signal: AbortSignal) => Promise<ImageSource>;
  #revision = 0;
  #destroyed = false;
  api: Pick<MediaApi, "prepare" | "sign" | "setThumbnails">;
  uppy: Uppy<Meta, AwsBody>;

  constructor(api: Pick<MediaApi, "prepare" | "sign" | "setThumbnails">, { month = currentMonth(), videoFactory = openVideo, imageFactory = openImage, uppyFactory = options => new Uppy<Meta, AwsBody>(options) }: MediaUploaderOptions = {}) {
    super({ month, files: [], uploaded: [], uploading: false, error: null, summary: "" });
    this.api = api;
    this.#videoFactory = videoFactory;
    this.#imageFactory = imageFactory;
    this.uppy = uppyFactory({
      restrictions: { maxFileSize: MAX_FILE_SIZE, maxNumberOfFiles: 40 },
      onBeforeFileAdded: file => {
        try {
          const parent = this.#parent(file);
          if (parent) {
            if (!this.#addingPoster || !this.#selections.has(parent)) throw new Error("Thumbnails must be generated by the uploader.");
            validateFile({ ...file, thumbnailFor: this.uppy.getFile(parent)?.name, dimensions: file.meta.monthlyDimensions });
          } else {
            validateFile(file);
            if (this.#originals().length >= 20) throw new Error("Choose at most 20 media files.");
          }
          return true;
        }
        catch (error) { this.setState({ error: asError(error) }); return false; }
      },
      onBeforeUpload: files => {
        try { this.#assertThumbnails(); return files; }
        catch (error) { this.setState({ error: asError(error) }); throw error; }
      },
    }).use(AwsS3<Meta, AwsBody>, {
      limit: 3,
      shouldUseMultipart: file => file.size !== null && file.size > MULTIPART_THRESHOLD,
      getChunkSize: () => PART_SIZE,
      generateObjectKey: file => {
        const proposal = crypto.randomUUID();
        this.#proposals.set(proposal, file);
        return proposal;
      },
      signRequest: request => this.signRequest(request),
    } satisfies AwsS3Options<Meta, AwsBody>);
    this.uppy.addPreProcessor(async () => { this.#assertThumbnails(); });
    this.uppy.on("file-added", file => {
      if (!this.#parent(file) && /^(image|video)\//.test(mediaType(file.name) ?? "")) this.#prepareMedia(file);
      this.#publish();
    });
    this.uppy.on("file-removed", file => {
      this.#disposeSelection(file.id);
      this.#items.delete(file.id);
      this.#reported.delete(file.id);
      this.#finalized.delete(file.id);
      this.#metadataErrors.delete(file.id);
      for (const [proposal, candidate] of this.#proposals) {
        if (candidate.id === file.id) this.#proposals.delete(proposal);
      }
      this.#publish();
    });
    for (const event of ["upload-progress", "upload-retry", "retry-all"] as const) {
      this.uppy.on(event, () => this.#publish());
    }
    this.uppy.on("upload", () => this.setState({ uploading: true, error: null, summary: "" }));
    this.uppy.on("restriction-failed", (file, error) => this.setState({ error }));
    this.uppy.on("upload-error", (file, error) => {
      this.setState({ error });
      this.#publish();
    });
    this.uppy.on("upload-success", (file, result) => {
      if (!file || !this.uppy.getFile(file.id)) return;
      const grant = result.body?.key ? this.#grants.get(result.body.key) : undefined;
      if (!grant || file.size === null) {
        this.setState({ error: new Error("Upload finished but its public URL is missing. Refresh the library.") });
        return;
      }
      const item = { key: grant.key, url: grant.url, size: file.size };
      this.#items.set(file.id, item);
      this.#publish();
    });
    this.uppy.on("complete", () => { this.#finishing = this.#finalize(); });
    this.uppy.on("cancel-all", () => {
      this.#revision++;
      this.#grants.clear();
      this.#proposals.clear();
      this.#metadataAbort?.abort();
      this.#items.clear();
      this.#finalized.clear();
      this.#metadataErrors.clear();
      this.#reported.clear();
      for (const id of [...this.#selections.keys()]) this.#disposeSelection(id);
      this.setState({ uploading: false, summary: "Uploads cancelled." });
      this.#publish();
    });
  }

  #publish() {
    const files = this.#originals().map(file => {
      const video = this.#selections.get(file.id);
      const poster = video?.posterId ? this.uppy.getFile(video.posterId) : undefined;
      const complete = !!file.progress.uploadComplete && (!video || ((!video.enabled || !!poster?.progress.uploadComplete) && this.#finalized.has(file.id)));
      if (complete && !this.#reported.has(file.id)) {
        const item = this.#mediaItem(file.id);
        if (item) {
          this.#reported.add(file.id);
          this.setState({ uploaded: [item, ...this.state.uploaded] });
        }
      }
      const size = (file.size ?? 0) + (poster?.size ?? 0);
      return {
        id: file.id, name: file.name, size: file.size ?? 0,
        progress: poster && size ? 100 * (Number(file.progress.bytesUploaded || 0) + Number(poster.progress.bytesUploaded || 0)) / size : file.progress.percentage || 0,
        complete, error: video?.error || file.error || poster?.error || this.#metadataErrors.get(file.id) || null,
        ...(video?.kind === "video" && { video: { duration: video.source?.duration ?? 0, time: video.time, posterUrl: video.posterUrl,
          checking: video.checking, editable: !file.progress.uploadStarted } }),
        ...(video?.kind === "image" && { image: { enabled: video.enabled, maxDimension: video.maxDimension,
          dimensions: video.dimensions, thumbnailUrl: video.posterUrl, checking: video.checking, editable: !file.progress.uploadStarted } }),
      };
    });
    this.setState({ files });
  }

  #parent(file: UppyFile<Meta, AwsBody>) {
    return typeof file.meta.monthlyThumbnailFor === "string" ? file.meta.monthlyThumbnailFor : undefined;
  }

  #originals() { return this.uppy.getFiles().filter(file => !this.#parent(file)); }

  #disposeSelection(id: string) {
    const video = this.#selections.get(id);
    if (!video) return;
    this.#selections.delete(id);
    video.abort.abort();
    video.source?.destroy();
    video.imageSource?.destroy();
    if (video.posterUrl) URL.revokeObjectURL(video.posterUrl);
    if (video.posterId) this.uppy.removeFile(video.posterId);
  }

  #prepareMedia(file: UppyFile<Meta, AwsBody>, enabled?: boolean, maxDimension = DEFAULT_THUMBNAIL_DIMENSION) {
    const kind = mediaType(file.name)?.startsWith("video/") ? "video" : "image";
    const video: ThumbnailSelection = { kind, enabled: kind === "video" || (enabled ?? (file.size !== null && file.size > IMAGE_THUMBNAIL_THRESHOLD)),
      maxDimension, abort: new AbortController(), pending: Promise.resolve(), checking: true, time: 0, error: null };
    this.#selections.set(file.id, video);
    if (!video.enabled) { video.checking = false; return; }
    video.pending = (async () => {
      try {
        if (!(file.data instanceof Blob)) throw new Error("Thumbnails require a local file that this browser can decode.");
        if (kind === "video") {
          const source = await this.#videoFactory(file.data, video.abort.signal);
          if (this.#selections.get(file.id) !== video) { source.destroy(); return; }
          video.source = source;
          await this.#capturePoster(file.id, video, Math.min(1, source.duration / 2));
        } else {
          const source = await this.#imageFactory(file.data, video.abort.signal);
          if (this.#selections.get(file.id) !== video) { source.destroy(); return; }
          video.imageSource = source;
          await this.#capturePoster(file.id, video, 0);
          source.destroy();
          video.imageSource = undefined;
        }
      } catch (error) {
        if (this.#selections.get(file.id) === video) {
          video.error = asError(error).message;
          this.setState({ error: new Error(`${file.name}: ${video.error}`) });
        }
      } finally {
        if (this.#selections.get(file.id) === video) { video.checking = false; this.#publish(); }
      }
    })();
  }

  async #capturePoster(id: string, video: ThumbnailSelection, time: number) {
    let captured: CapturedThumbnail;
    if (video.kind === "video") {
      if (!video.source) throw new Error("Wait for video decoding to finish.");
      if (!Number.isFinite(time) || time < 0 || time >= video.source.duration) throw new Error("Choose a frame within the video.");
      captured = await video.source.capture(time);
    } else {
      if (!video.imageSource) throw new Error("Wait for image decoding to finish.");
      captured = await video.imageSource.capture(video.maxDimension);
    }
    if (this.#selections.get(id) !== video) return;
    const { blob, width, height } = captured;
    const dimensions = `${width}x${height}`;
    const file = this.uppy.getFile(id);
    if (!file) return;
    validateFile({ name: "thumbnail.jpg", size: blob.size, thumbnailFor: file.name, dimensions });
    if (video.posterId) this.uppy.removeFile(video.posterId);
    if (video.posterUrl) URL.revokeObjectURL(video.posterUrl);
    video.posterId = undefined;
    video.posterUrl = undefined;
    this.#addingPoster = true;
    try {
      video.posterId = this.uppy.addFile({
        name: thumbnailKey(uploadFilename(file.name), dimensions), type: "image/jpeg", data: blob,
        meta: { monthlyThumbnailFor: id, monthlyDimensions: dimensions },
      });
      video.posterUrl = URL.createObjectURL(blob);
      video.time = time;
      video.dimensions = dimensions;
      video.error = null;
    } finally { this.#addingPoster = false; }
  }

  async selectPoster(id: string, time: number) {
    const video = this.#selections.get(id);
    const file = this.uppy.getFile(id);
    if (!video || video.kind !== "video" || !file || video.checking || this.state.uploading || file.progress.uploadStarted) return false;
    video.checking = true;
    this.setState({ error: null });
    this.#publish();
    let success = false;
    video.pending = (async () => {
      try { await this.#capturePoster(id, video, time); success = this.#selections.get(id) === video; }
      catch (error) {
        if (this.#selections.get(id) === video) {
          video.error = asError(error).message;
          this.setState({ error: new Error(`${file.name}: ${video.error}`) });
        }
      } finally {
        if (this.#selections.get(id) === video) { video.checking = false; this.#publish(); }
      }
    })();
    await video.pending;
    return success;
  }

  async configureImageThumbnail(id: string, enabled: boolean, maxDimension = DEFAULT_THUMBNAIL_DIMENSION) {
    const file = this.uppy.getFile(id);
    const selection = this.#selections.get(id);
    if (!file || selection?.kind !== "image" || this.state.uploading || file.progress.uploadStarted) return false;
    if (!Number.isInteger(maxDimension) || maxDimension < 320 || maxDimension > 2048) {
      this.setState({ error: new Error("Choose a thumbnail longest edge between 320 and 2048 pixels.") });
      return false;
    }
    this.setState({ error: null });
    this.#disposeSelection(id);
    this.#prepareMedia(file, enabled, maxDimension);
    this.#publish();
    const current = this.#selections.get(id)!;
    await current.pending;
    return this.#selections.get(id) === current && !current.error;
  }

  #assertThumbnails() {
    for (const file of this.#originals()) {
      if (!/^(image|video)\//.test(mediaType(file.name) ?? "")) continue;
      const video = this.#selections.get(file.id);
      if (!video || (video.enabled && (video.checking || video.error || !video.posterId || !this.uppy.getFile(video.posterId)))) {
        throw new Error(`${file.name}: ${video?.error || "Wait for decoding and thumbnail preparation before uploading."}`);
      }
    }
  }

  async ready() {
    await Promise.all([...this.#selections.values()].map(video => video.pending));
    this.#assertThumbnails();
  }

  #mediaItem(id: string): MediaItem | undefined {
    const item = this.#items.get(id);
    if (!item) return;
    const video = this.#selections.get(id);
    if (!video?.enabled) return item;
    const poster = video.posterId ? this.#items.get(video.posterId) : undefined;
    if (!poster || !video.dimensions) return;
    return { ...item, thumbnails: { [video.dimensions]: { ...poster, ...(video.kind === "video" && { time: video.time }) } } };
  }

  async #finalize() {
    const revision = this.#revision;
    const abort = new AbortController();
    this.#metadataAbort = abort;
    await Promise.all(this.#originals().map(async file => {
      const selection = this.#selections.get(file.id);
      const thumbnail = selection?.posterId ? this.uppy.getFile(selection.posterId) : undefined;
      if (!selection || this.#finalized.has(file.id) || !file.progress.uploadComplete ||
          (selection.enabled && !thumbnail?.progress.uploadComplete)) return;
      const item = this.#mediaItem(file.id);
      if (!item) return;
      try {
        await this.api.setThumbnails(item, this.state.month, abort.signal);
        if (revision !== this.#revision || !this.uppy.getFile(file.id)) return;
        this.#finalized.add(file.id);
        this.#metadataErrors.delete(file.id);
      } catch (error) {
        if (revision !== this.#revision) return;
        this.#metadataErrors.set(file.id, asError(error).message);
        this.setState({ error: asError(error) });
      }
      this.#publish();
    }));
    if (revision !== this.#revision) return;
    this.#publish();
    this.setState({ uploading: false,
      summary: `${this.state.files.filter(file => file.complete).length} uploaded; ${this.state.files.filter(file => !file.complete).length} failed.` });
  }

  async signRequest(request: SignRequest) {
    let grant = this.#grants.get(request.key);
    if (!grant) {
      const file = this.#proposals.get(request.key);
      if (!file || request.uploadId) throw new Error("Upload authorization is missing. Remove the file and add it again.");
      this.#assertThumbnails();
      const parent = this.#parent(file);
      const proposal = { name: file.name, size: file.size,
        ...(parent && { thumbnailFor: this.uppy.getFile(parent)?.name, dimensions: file.meta.monthlyDimensions }) };
      validateFile(proposal);
      const revision = this.#revision;
      grant = await this.api.prepare(proposal, this.state.month);
      if (revision !== this.#revision || !this.uppy.getFile(file.id)) throw new Error("Upload authorization changed. Remove the file and add it again.");
      this.#grants.set(request.key, grant);
      this.#grants.set(grant.key, grant);
    }
    return this.api.sign(request, grant);
  }

  addFiles(files: Iterable<File>) {
    if (this.state.uploading) {
      this.setState({ error: new Error("Wait for the current upload to finish before adding files.") });
      return;
    }
    this.setState({ error: null, summary: "" });
    for (const file of this.state.files) {
      if (file.complete) this.removeFile(file.id);
    }
    for (const file of files) {
      try { this.uppy.addFile({ name: file.name, type: mediaType(file.name) ?? undefined, data: file }); }
      catch (error) { this.setState({ error: asError(error) }); }
    }
    this.#publish();
  }

  setMonth(month: string) {
    try {
      validateMonth(month);
      if (this.state.uploading || this.uppy.getFiles().some(file => file.progress.uploadStarted && !file.progress.uploadComplete) ||
          this.state.files.some(file => !file.complete && this.uppy.getFile(file.id)?.progress.uploadStarted)) {
        throw new Error("Remove partially uploaded files before changing the upload month.");
      }
      this.setState({ month, error: null });
      return true;
    } catch (error) { this.setState({ error: asError(error) }); return false; }
  }

  removeFile(id: string) {
    if (this.state.uploading) return;
    this.uppy.removeFile(id);
    this.#publish();
  }

  completedMedia() {
    return this.state.files.filter(file => file.complete).map(file => {
      const item = this.#mediaItem(file.id);
      if (!item) throw new Error("Uploaded media is missing. Remove the file and upload it again.");
      return item;
    });
  }

  clear() {
    this.cancel();
    this.#items.clear();
    this.setState({ uploaded: [], error: null, summary: "" });
  }

  async upload() {
    if (this.state.uploading || this.#destroyed) return;
    const revision = this.#revision;
    this.setState({ error: null, uploading: true });
    try {
      await this.ready();
      if (revision !== this.#revision) return;
      if (!this.state.files.length) throw new Error("Choose files to upload.");
      let result;
      if (this.uppy.getFiles().some(file => !file.progress.uploadComplete)) {
        result = await this.uppy.upload();
        await this.#finishing;
      } else await this.#finalize();
      return result;
    } catch (error) {
      if (revision === this.#revision) this.setState({ uploading: false, error: asError(error) });
    }
  }

  cancel() { this.uppy.cancelAll(); }
  destroy() {
    this.#destroyed = true;
    this.#revision++;
    this.#metadataAbort?.abort();
    for (const id of [...this.#selections.keys()]) this.#disposeSelection(id);
    this.uppy.destroy();
  }
}
